import * as React from "react";
import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { interactive?: boolean }
>(({ className, interactive = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-[8px] border border-[#e5e7eb] dark:border-[#27272a] bg-white dark:bg-[#121215] text-[#111827] dark:text-[#f4f4f5] shadow-none",
      interactive &&
        "transition-colors hover:border-[#fb6b6a] dark:hover:border-[#fb6b6a] cursor-pointer",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

